"""Single-owner OAuth provider for the official MCP SDK.

No upstream API key is ever issued to a client. Client registrations and tokens
are signed to survive free-service restarts; login requests and codes are short
lived and single-use. No user database is introduced.
"""
from __future__ import annotations

import hashlib
import hmac
import html
import json
import re
import secrets
import time
from urllib.parse import urlencode, urlsplit

import jwt
from mcp.server.auth.provider import (AccessToken, AuthorizationCode,
    AuthorizeError, RefreshToken, RegistrationError, TokenError)
from mcp.shared.auth import OAuthClientInformationFull, OAuthToken
from starlette.responses import HTMLResponse, RedirectResponse

SCOPE = 'transactions:read'


def password_hash(password: str, salt: str | None = None) -> str:
    salt = salt or secrets.token_hex(16)
    digest = hashlib.scrypt(password.encode(), salt=bytes.fromhex(salt), n=16384, r=8, p=1).hex()
    return f'scrypt${salt}${digest}'


def valid_redirect(value: str) -> bool:
    u = urlsplit(value)
    return (u.scheme == 'https' and u.netloc == 'chatgpt.com' and not u.query and not u.fragment
            and (u.path == '/connector_platform_oauth_redirect'
                 or re.fullmatch(r'/connector/oauth/[A-Za-z0-9_-]+', u.path) is not None))


class OwnerOAuth:
    def __init__(self, origin: str, signing_key: str, owner_hash: str):
        self.origin = origin.rstrip('/')
        u = urlsplit(self.origin)
        if u.scheme != 'https' or not u.netloc or u.username or u.password or u.path or u.query or u.fragment:
            raise ValueError('MCP_PUBLIC_URL must be an HTTPS origin')
        if len(signing_key) < 48:
            raise ValueError('MCP_TOKEN_SECRET must contain at least 48 characters')
        if not re.fullmatch(r'scrypt\$[0-9a-f]{32}\$[0-9a-f]{128}', owner_hash):
            raise ValueError('MCP_LOGIN_PASSWORD_HASH must be generated by the setup helper')
        self.key, self.owner_hash = signing_key, owner_hash
        self.issuer = self.origin + '/'
        self.resource = self.origin + '/mcp'
        self.pending = {}
        self.codes = {}
        self.revoked = {}
        self.attempts = []

    def _prune(self):
        now = time.time()
        self.pending = {k: v for k, v in self.pending.items() if v['expires'] > now}
        self.codes = {k: v for k, v in self.codes.items() if v.expires_at > now}
        self.revoked = {k: v for k, v in self.revoked.items() if v > now}
        self.attempts = [t for t in self.attempts if t > now - 300]

    def _encode(self, kind, payload, ttl=None, audience=None):
        data = {'iss': self.issuer, 'aud': audience or self.resource, 'kind': kind,
                'iat': int(time.time()), 'jti': secrets.token_hex(16), **payload}
        if ttl is not None:
            data['exp'] = int(time.time()) + ttl
        return jwt.encode(data, self.key, algorithm='HS256')

    def _decode(self, token, kind, audience=None):
        try:
            data = jwt.decode(token, self.key, algorithms=['HS256'], issuer=self.issuer,
                              audience=audience or self.resource,
                              options={'require': ['iss','aud','kind','iat','jti'] + ([] if kind == 'client' else ['exp'])})
            if data['kind'] != kind or data['jti'] in self.revoked:
                return None
            return data
        except (jwt.PyJWTError, TypeError, ValueError):
            return None

    def _client_secret(self, nonce):
        return hmac.new(self.key.encode(), ('oauth-client-secret:' + nonce).encode(), hashlib.sha256).hexdigest()

    async def register_client(self, client):
        if not client.redirect_uris or len(client.redirect_uris) > 4 or not all(valid_redirect(str(u)) for u in client.redirect_uris):
            raise RegistrationError('invalid_redirect_uri', 'Only documented ChatGPT callback URLs are allowed')
        if client.token_endpoint_auth_method not in ('none', 'client_secret_post', 'client_secret_basic'):
            raise RegistrationError('invalid_client_metadata', 'Unsupported client authentication method')
        if client.scope and set(client.scope.split()) != {SCOPE}:
            raise RegistrationError('invalid_client_metadata', 'Unsupported scope')
        nonce = secrets.token_hex(24)
        metadata = client.model_dump(mode='json')
        for k in ('client_id','client_secret','client_secret_expires_at'):
            metadata.pop(k, None)
        if len(json.dumps(metadata).encode()) > 2048:
            raise RegistrationError('invalid_client_metadata', 'Client metadata is too large')
        # The client ID contains public metadata only, never its derived secret.
        client.client_id = self._encode('client', {'metadata': metadata, 'nonce': nonce}, audience=self.origin)
        client.client_secret = None if client.token_endpoint_auth_method == 'none' else self._client_secret(nonce)
        client.client_secret_expires_at = None

    async def get_client(self, client_id):
        data = self._decode(client_id, 'client', self.origin)
        if not data:
            return None
        metadata = data['metadata']
        secret = None if metadata['token_endpoint_auth_method'] == 'none' else self._client_secret(data['nonce'])
        return OAuthClientInformationFull(**metadata, client_id=client_id, client_secret=secret)

    async def authorize(self, client, params):
        self._prune()
        if params.resource != self.resource or set(params.scopes or []) != {SCOPE}:
            raise AuthorizeError('invalid_scope', 'The exact MCP resource and read scope are required')
        if not valid_redirect(str(params.redirect_uri)):
            raise AuthorizeError('invalid_request', 'Invalid redirect URI')
        if len(self.pending) >= 128:
            raise AuthorizeError('temporarily_unavailable', 'Please try again later')
        request_id = secrets.token_urlsafe(32)
        self.pending[request_id] = {'client': client, 'params': params,
                                    'csrf': secrets.token_urlsafe(32), 'expires': time.time() + 300}
        return self.origin + '/login?' + urlencode({'request_id': request_id})

    async def login(self, request):
        self._prune()
        form = await request.form() if request.method == 'POST' else None
        rid = str(form.get('request_id', '')) if form is not None else request.query_params.get('request_id', '')
        pending = self.pending.get(rid)
        headers = {'Cache-Control': 'no-store', 'Referrer-Policy': 'no-referrer',
                   'Content-Security-Policy': "default-src 'none'; style-src 'unsafe-inline'; form-action 'self'; frame-ancestors 'none'; base-uri 'none'",
                   'X-Content-Type-Options': 'nosniff'}
        if not pending:
            return HTMLResponse('연결 요청이 만료됐습니다. ChatGPT에서 다시 연결해주세요.', status_code=400, headers=headers)
        csrf = pending['csrf']
        if form is not None:
            if (not hmac.compare_digest(str(form.get('csrf', '')).encode(), csrf.encode())
                    or not hmac.compare_digest(request.cookies.get('gr_login_csrf', '').encode(), csrf.encode())):
                return HTMLResponse('Invalid login request', status_code=403, headers=headers)
            if len(self.attempts) >= 20:
                return HTMLResponse('잠시 후 다시 시도해주세요.', status_code=429, headers=headers)
            self.attempts.append(time.time())
            password = str(form.get('password', ''))
            salt = self.owner_hash.split('$')[1]
            if len(password) > 256 or not hmac.compare_digest(password_hash(password, salt), self.owner_hash):
                return HTMLResponse('암호가 일치하지 않습니다. ChatGPT에서 연결을 다시 시작해주세요.', status_code=401, headers=headers)
            # No await between removal and creation: only one request can consume it.
            self.pending.pop(rid)
            params, client = pending['params'], pending['client']
            code = secrets.token_urlsafe(32)
            self.codes[code] = AuthorizationCode(code=code, client_id=client.client_id,
                scopes=params.scopes, expires_at=time.time() + 120, code_challenge=params.code_challenge,
                redirect_uri=params.redirect_uri, redirect_uri_provided_explicitly=params.redirect_uri_provided_explicitly,
                resource=self.resource)
            query = {'code': code, 'iss': self.issuer}
            if params.state is not None:
                query['state'] = params.state
            result = RedirectResponse(str(params.redirect_uri) + '?' + urlencode(query), status_code=303, headers=headers)
            result.delete_cookie('gr_login_csrf', path='/login', secure=True, httponly=True, samesite='lax')
            return result
        page = f'''<!doctype html><html lang="ko"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>GAP-RADAR 연결 승인</title><style>body{{font:18px sans-serif;max-width:440px;margin:60px auto;padding:20px}}input,button{{box-sizing:border-box;width:100%;padding:14px;margin-top:12px}}button{{background:#185adb;color:white;border:0;border-radius:8px}}</style>
<h1>GAP-RADAR 연결</h1><p>ChatGPT에 실거래 읽기 전용 접근을 허용합니다.</p>
<p>API 키가 아닌, 이번 연결용으로 만든 전용 암호를 입력하세요.</p>
<form method="post" action="/login"><input type="hidden" name="request_id" value="{html.escape(rid, quote=True)}">
<input type="hidden" name="csrf" value="{csrf}"><label>연결용 암호<input name="password" type="password" required maxlength="256" autocomplete="current-password"></label>
<button type="submit">실거래 조회 연결 허용</button></form></html>'''
        result = HTMLResponse(page, headers=headers)
        result.set_cookie('gr_login_csrf', csrf, max_age=300, path='/login', secure=True, httponly=True, samesite='lax')
        return result

    async def load_authorization_code(self, client, authorization_code):
        self._prune()
        return self.codes.get(authorization_code)

    def _tokens(self, client, scopes):
        access = self._encode('access', {'client_id': client.client_id, 'scopes': scopes}, 3600)
        # Public clients must reauthorize; refresh tokens require a client secret.
        refresh = None if client.token_endpoint_auth_method == 'none' else self._encode(
            'refresh', {'client_id': client.client_id, 'scopes': scopes}, 30 * 86400)
        return OAuthToken(access_token=access, token_type='Bearer', expires_in=3600,
                          refresh_token=refresh, scope=' '.join(scopes))

    async def exchange_authorization_code(self, client, authorization_code):
        if self.codes.pop(authorization_code.code, None) is None:
            raise TokenError('invalid_grant', 'Authorization code already used')
        return self._tokens(client, authorization_code.scopes)

    async def load_access_token(self, token):
        data = self._decode(token, 'access')
        if not data or set(data.get('scopes', [])) != {SCOPE}:
            return None
        return AccessToken(token=token, client_id=data['client_id'], scopes=data['scopes'],
                           expires_at=data['exp'], resource=self.resource)

    async def load_refresh_token(self, client, refresh_token):
        data = self._decode(refresh_token, 'refresh')
        if not data or data['client_id'] != client.client_id or client.token_endpoint_auth_method == 'none':
            return None
        return RefreshToken(token=refresh_token, client_id=client.client_id, scopes=data['scopes'],
                            expires_at=data['exp'], resource=self.resource)

    async def exchange_refresh_token(self, client, refresh_token, scopes):
        self._prune()
        data = self._decode(refresh_token.token, 'refresh')
        if not data or data['client_id'] != client.client_id:
            raise TokenError('invalid_grant', 'Invalid refresh token')
        if len(self.revoked) >= 10000:
            raise TokenError('invalid_grant', 'Please reauthorize later')
        self.revoked[data['jti']] = data['exp']
        return self._tokens(client, scopes)

    async def revoke_token(self, token):
        for kind in ('access', 'refresh'):
            data = self._decode(token.token, kind)
            if data:
                self.revoked[data['jti']] = data['exp']
